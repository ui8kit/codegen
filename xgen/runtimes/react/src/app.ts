// Scaffold of the React host app: config, entry, and the App that renders the screen named by the URL (/<key>/#/<route>).
// Screens load on demand (one chunk each); content, data and menus come from the shared package, emitted once.
import { readFileSync } from "node:fs";
import { join } from "node:path";
import type { AppSpec, ScreenSpec } from "@ui8kit/xgen-screens";
import { BANNER, HOST_GEN, SHARED, appCss, hostUrlAsset, indexHtml, jsonFile, screenKey, viteConfig, withBanner, type GeneratedFile } from "@ui8kit/xgen-runtime-core";

const UI = "@ui8kit/react-ui";

export function appScaffold(app: AppSpec, screens: ScreenSpec[]): GeneratedFile[] {
  const loaders = screens.map((s) => `  ${JSON.stringify(screenKey(s.id))}: () => import("./screens/${s.name}").then((m) => ({ default: m.${s.name} })),`);
  const appTsx = [
    `// ${BANNER}`,
    `import { Block, Link, List, ListItem, Title } from "${UI}";`,
    `import { SCREENS } from "${SHARED}/screens";`,
    `import { useUrl } from "./runtime/url";`,
    `import { ScreenOutlet, type ScreenModule } from "./runtime/ScreenOutlet";`,
    ``,
    `/** one chunk per screen: a landing is a screen spec, not an app */`,
    `const LOADERS: Record<string, () => Promise<ScreenModule>> = {`,
    ...loaders,
    `};`,
    ``,
    `export function App({ screen, title }: { screen: string; title: string }) {`,
    `  const url = useUrl();`,
    `  const load = LOADERS[screen];`,
    `  if (load) return <ScreenOutlet load={load} url={url} />;`,
    `  return (`,
    `    <Block tag="main" id="main-content" className="mx-auto w-full max-w-3xl px-4 py-12" data-testid="host-index">`,
    `      <Title as={1} size="2xl" weight="semibold">{title}</Title>`,
    `      <List className="mt-6 grid gap-2">`,
    `        {SCREENS.map((s) => <ListItem key={s.key}><Link className="underline" href={\`/\${s.key}/\`} data-testid="host-screen">{s.key}</Link></ListItem>)}`,
    `      </List>`,
    `    </Block>`,
    `  );`,
    `}`,
    ``,
  ].join("\n");
  const assets = join(import.meta.dir, "..", "assets");
  return [
    jsonFile("package.json", {
      name: app.name, private: true, version: "0.0.0", type: "module",
      description: `Generated by xgen from xgen.app.json: the React 19 host of ${screens.length} screens (/<screen>/#/<route>). Generated under ${HOST_GEN}/; src/ is the front controller.`,
      ui8kit: { runtime: "react", generated: true, kit: [`${HOST_GEN}/runtime`], composition: [`${HOST_GEN}/App.tsx`, `${HOST_GEN}/screens`], blockRoot: [`${HOST_GEN}/App.tsx`, `${HOST_GEN}/screens`] },
      scripts: { dev: "vite", build: "vite build", preview: "vite preview", check: "tsc --noEmit -p tsconfig.json" },
      dependencies: { [SHARED]: "workspace:*", [UI]: "workspace:*", react: "^19.2.0", "react-dom": "^19.2.0" },
      devDependencies: { "@tailwindcss/vite": "^4.3.3", "@types/react": "^19.2.0", "@types/react-dom": "^19.2.0", "@vitejs/plugin-react": "^6.1.0", tailwindcss: "^4.3.3", typescript: "~6.0.2", vite: "^8.3.0" },
    }),
    { path: "index.html", contents: indexHtml(app).replace("__EXT__", "tsx") },
    viteConfig([`import react from "@vitejs/plugin-react";`], "react()", app),
    { path: "tsconfig.json", contents: `// ${BANNER}\n{\n  "compilerOptions": {\n    "target": "ES2023", "lib": ["ES2023", "DOM", "DOM.Iterable"], "module": "ESNext", "moduleResolution": "bundler", "jsx": "react-jsx",\n    "strict": true, "noEmit": true, "skipLibCheck": true, "resolveJsonModule": true, "isolatedModules": true, "verbatimModuleSyntax": true,\n    "allowImportingTsExtensions": true, "types": ["vite/client"]\n  },\n  "include": ["src", "${HOST_GEN}"]\n}\n` },
    appCss(UI),
    { path: "src/main.tsx", contents: withBanner(`import { StrictMode } from "react";\nimport { createRoot } from "react-dom/client";\nimport "./app.css";\nimport { bootScreen, screenKeyOf } from "${SHARED}/screens";\nimport { App } from "../${HOST_GEN}/App";\n\nconst screen = screenKeyOf(location);\nconst title = ${JSON.stringify(app.title)};\nbootScreen(screen, ${JSON.stringify(app.theme)}, title);\ncreateRoot(document.getElementById("app")!).render(\n  <StrictMode>\n    <App screen={screen} title={title} />\n  </StrictMode>,\n);\n`) },
    { path: `${HOST_GEN}/App.tsx`, contents: appTsx },
    hostUrlAsset("url.ts", readFileSync(join(assets, "url.ts"), "utf8")),
    hostUrlAsset("ScreenOutlet.tsx", readFileSync(join(assets, "ScreenOutlet.tsx"), "utf8")),
  ];
}
