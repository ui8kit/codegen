import { expect, test } from "bun:test";
import { join } from "node:path";
import { planBuild } from "@ui8kit/xgen-generator";
import { emitJinjaBrick, jinja } from "../src/index";

const plan = planBuild(join(import.meta.dir, "..", "..", "..", ".."));

test("every brick makes Jinja templates with the banner and no Twig-only syntax, the same twice", () => {
  for (const { brick } of plan.bricks) {
    if (brick.id === "ui.lucide-icon") continue; // an asset, not emitted
    const a = emitJinjaBrick(brick, "x", jinja), b = emitJinjaBrick(brick, "x", jinja);
    expect(a.map((f) => f.contents)).toEqual(b.map((f) => f.contents));
    for (const f of a.filter((x) => x.path.endsWith(".html.j2"))) {
      expect(f.contents.startsWith("{#- Code generated by xgen. DO NOT EDIT.")).toBe(true);
      expect(f.contents).not.toMatch(/\?\?|\|raw|with_context|\{%-? elseif| is not null|\bp\.[A-Z]/);
    }
  }
});

test("the jinja2 package is a target of the plan with organisms, the Python helpers and the ui8kit zones", () => {
  const t = plan.targets.find((x) => x.runtime === "jinja2")!;
  expect(t.files.some((f) => f.path === "blocks/pager.html.j2")).toBe(true);
  expect(t.files.some((f) => f.path === "py/ui8kit_jinja/runtime.py")).toBe(true);
  expect(t.files.find((f) => f.path === "requirements.txt")!.contents).toContain("Jinja2");
  const pkg = JSON.parse(t.files.find((f) => f.path === "package.json")!.contents) as { ui8kit: { kit: string[]; composition: string[]; blockRoot: string[] } };
  expect(pkg.ui8kit.kit).toEqual(["ui", "py"]);
  expect(pkg.ui8kit.composition).toEqual(["blocks"]);
  expect(pkg.ui8kit.blockRoot.length).toBeGreaterThan(0);
});
