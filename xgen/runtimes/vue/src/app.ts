// Scaffold of the Vue host app: config, entry, and the App that renders the screen named by the URL (/<key>/#/<route>).
// Screens load on demand (one chunk each); content, data and menus come from the shared package, emitted once.
import { readFileSync } from "node:fs";
import { join } from "node:path";
import type { AppSpec, ScreenSpec } from "@ui8kit/xgen-screens";
import { BANNER, HOST_GEN, SHARED, appCss, hostUrlAsset, indexHtml, jsonFile, screenKey, viteConfig, withBanner, type GeneratedFile } from "@ui8kit/xgen-runtime-core";

const UI = "@ui8kit/vue-ui";

export function appScaffold(app: AppSpec, screens: ScreenSpec[]): GeneratedFile[] {
  const loaders = screens.map((s) => `  ${JSON.stringify(screenKey(s.id))}: () => import("./screens/${s.name}.vue"),`);
  const appVue = [
    `<!-- ${BANNER} -->`,
    `<script setup lang="ts">`,
    `import type { Component } from "vue";`,
    `import { Block, Link, List, ListItem, Title } from "${UI}";`,
    `import { SCREENS } from "${SHARED}/screens";`,
    `import { url } from "./runtime/url";`,
    `import ScreenOutlet from "./runtime/ScreenOutlet.vue";`,
    ``,
    `const { screen, title } = defineProps<{ screen: string; title: string }>();`,
    ``,
    `/** one chunk per screen: a landing is a screen spec, not an app */`,
    `const LOADERS: Record<string, () => Promise<{ default: Component }>> = {`,
    ...loaders,
    `};`,
    `const load = LOADERS[screen];`,
    `</script>`,
    ``,
    `<template>`,
    `  <Block v-if="!load" tag="main" id="main-content" class="mx-auto w-full max-w-3xl px-4 py-12" data-testid="host-index">`,
    `    <Title :as="1" size="2xl" weight="semibold">{{ title }}</Title>`,
    `    <List class="mt-6 grid gap-2">`,
    `      <ListItem v-for="s in SCREENS" :key="s.key"><Link class="underline" :href="\`/\${s.key}/\`" data-testid="host-screen">{{ s.key }}</Link></ListItem>`,
    `    </List>`,
    `  </Block>`,
    `  <ScreenOutlet v-else :load="load" :url="url" />`,
    `</template>`,
    ``,
  ].join("\n");
  const assets = join(import.meta.dir, "..", "assets");
  return [
    jsonFile("package.json", {
      name: app.name, private: true, version: "0.0.0", type: "module",
      description: `Generated by xgen from xgen.app.json: the Vue 3 host of ${screens.length} screens (/<screen>/#/<route>). Generated under ${HOST_GEN}/; src/ is the front controller.`,
      ui8kit: { runtime: "vue", generated: true, kit: [`${HOST_GEN}/runtime`], composition: [`${HOST_GEN}/App.vue`, `${HOST_GEN}/screens`], blockRoot: [`${HOST_GEN}/App.vue`, `${HOST_GEN}/screens`] },
      scripts: { dev: "vite", build: "vite build", preview: "vite preview", check: "vue-tsc --noEmit -p tsconfig.json" },
      dependencies: { [SHARED]: "workspace:*", [UI]: "workspace:*", vue: "^3.5.43" },
      devDependencies: { "@tailwindcss/vite": "^4.3.3", "@vitejs/plugin-vue": "^6.0.9", tailwindcss: "^4.3.3", typescript: "~6.0.2", vite: "^8.3.0", "vue-tsc": "^3.3.12" },
    }),
    { path: "index.html", contents: indexHtml(app).replace("__EXT__", "ts") },
    viteConfig([`import vue from "@vitejs/plugin-vue";`], "vue()", app),
    {
      path: "tsconfig.json",
      contents: `// ${BANNER}\n{\n  "compilerOptions": {\n    "target": "ES2023", "lib": ["ES2023", "DOM", "DOM.Iterable"], "module": "ESNext", "moduleResolution": "bundler", "jsx": "preserve",\n    "strict": true, "noEmit": true, "skipLibCheck": true, "resolveJsonModule": true, "isolatedModules": true, "verbatimModuleSyntax": true,\n    "types": ["vite/client"]\n  },\n  "include": ["src/**/*.ts", "src/**/*.vue", "${HOST_GEN}/**/*.ts", "${HOST_GEN}/**/*.vue"]\n}\n`,
    },
    appCss(UI),
    { path: "src/main.ts", contents: withBanner(`import { createApp } from "vue";\nimport "./app.css";\nimport { bootScreen, screenKeyOf } from "${SHARED}/screens";\nimport App from "../${HOST_GEN}/App.vue";\n\nconst screen = screenKeyOf(location);\nconst title = ${JSON.stringify(app.title)};\nbootScreen(screen, ${JSON.stringify(app.theme)}, title);\ncreateApp(App, { screen, title }).mount("#app");\n`) },
    { path: `${HOST_GEN}/App.vue`, contents: appVue },
    hostUrlAsset("url.ts", readFileSync(join(assets, "url.ts"), "utf8")),
    { path: `${HOST_GEN}/runtime/ScreenOutlet.vue`, contents: `<!-- ${BANNER} -->\n` + readFileSync(join(assets, "ScreenOutlet.vue"), "utf8").replace(/from "\.\/core"/g, `from "${SHARED}/runtime/core"`) },
  ];
}
