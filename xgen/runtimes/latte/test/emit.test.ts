import { expect, test } from "bun:test";
import { join } from "node:path";
import { planBuild } from "@ui8kit/xgen-generator";
import { emitLatteBrick, latte } from "../src/index";

const plan = planBuild(join(import.meta.dir, "..", "..", "..", ".."));

test("every brick makes Latte templates with the banner and no Twig syntax, the same twice", () => {
  for (const { brick } of plan.bricks) {
    if (brick.id === "ui.lucide-icon") continue; // an asset, not emitted
    const a = emitLatteBrick(brick, "x", latte), b = emitLatteBrick(brick, "x", latte);
    expect(a.map((f) => f.contents)).toEqual(b.map((f) => f.contents));
    for (const f of a.filter((x) => x.path.endsWith(".latte"))) {
      expect(f.contents.startsWith("{* Code generated by xgen. DO NOT EDIT.")).toBe(true);
      expect(f.contents).not.toMatch(/\{\{|\{%|\|raw|\bp\.[A-Z]|<\{=/);
    }
  }
});

test("the latte package is a target of the plan with organisms, the PHP helpers and the ui8kit zones", () => {
  const t = plan.targets.find((x) => x.runtime === "latte")!;
  expect(t.files.some((f) => f.path === "blocks/pager.latte")).toBe(true);
  expect(t.files.find((f) => f.path === "php/Runtime.php")!.contents).toContain("namespace UI8Kit\\Latte;");
  expect(t.files.find((f) => f.path === "composer.json")!.contents).toContain("latte/latte");
  const pkg = JSON.parse(t.files.find((f) => f.path === "package.json")!.contents) as { ui8kit: { kit: string[]; composition: string[]; blockRoot: string[] } };
  expect(pkg.ui8kit.kit).toEqual(["ui", "php"]);
  expect(pkg.ui8kit.composition).toEqual(["blocks"]);
  expect(pkg.ui8kit.blockRoot.length).toBeGreaterThan(0);
});
