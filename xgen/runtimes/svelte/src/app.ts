// Scaffold of the Svelte host app: config, entry, and the App that renders the screen named by the URL (/<key>/#/<route>).
// Screens load on demand (one chunk each); content, data and menus come from the shared package, emitted once.
import { readFileSync } from "node:fs";
import { join } from "node:path";
import type { AppSpec, ScreenSpec } from "@ui8kit/xgen-screens";
import { BANNER, HOST_GEN, SHARED, appCss, hostUrlAsset, indexHtml, jsonFile, screenKey, viteConfig, withBanner, type GeneratedFile } from "@ui8kit/xgen-runtime-core";

const UI = "@ui8kit/svelte-ui";

export function appScaffold(app: AppSpec, screens: ScreenSpec[]): GeneratedFile[] {
  const loaders = screens.map((s) => `    ${JSON.stringify(screenKey(s.id))}: () => import("./screens/${s.name}.svelte"),`);
  const appSvelte = [
    `<!-- ${BANNER} -->`,
    `<script lang="ts">`,
    `  import type { Component } from "svelte";`,
    `  import { SCREENS } from "${SHARED}/screens";`,
    `  import type { UrlPort } from "${SHARED}/runtime/core";`,
    `  import { Block, Link, List, ListItem, Title } from "${UI}";`,
    `  import { url } from "./runtime/url.svelte";`,
    ``,
    `  let { screen, title }: { screen: string; title: string } = $props();`,
    ``,
    `  /** one chunk per screen: a landing is a screen spec, not an app */`,
    `  const LOADERS: Record<string, () => Promise<{ default: Component<{ url: UrlPort }> }>> = {`,
    ...loaders,
    `  };`,
    `  const load = $derived(LOADERS[screen]);`,
    `</script>`,
    ``,
    `{#if !load}`,
    `  <Block tag="main" id="main-content" class="mx-auto w-full max-w-3xl px-4 py-12" data-testid="host-index">`,
    `    <Title as={1} size="2xl" weight="semibold">{title}</Title>`,
    `    <List class="mt-6 grid gap-2">`,
    `      {#each SCREENS as s (s.key)}`,
    `        <ListItem><Link class="underline" href={\`/\${s.key}/\`} data-testid="host-screen">{s.key}</Link></ListItem>`,
    `      {/each}`,
    `    </List>`,
    `  </Block>`,
    `{:else}`,
    `  {#await load() then mod}`,
    `    <mod.default {url} />`,
    `  {/await}`,
    `{/if}`,
    ``,
  ].join("\n");
  const assets = join(import.meta.dir, "..", "assets");
  return [
    jsonFile("package.json", {
      name: app.name, private: true, version: "0.0.0", type: "module",
      description: `Generated by xgen from xgen.app.json: the Svelte 5 host of ${screens.length} screens (/<screen>/#/<route>). Generated under ${HOST_GEN}/; src/ is the front controller.`,
      ui8kit: { runtime: "svelte", generated: true, kit: [`${HOST_GEN}/runtime`], composition: [`${HOST_GEN}/App.svelte`, `${HOST_GEN}/screens`], blockRoot: [`${HOST_GEN}/App.svelte`, `${HOST_GEN}/screens`] },
      scripts: { dev: "vite", build: "vite build", preview: "vite preview", check: "svelte-check --tsconfig ./tsconfig.json" },
      dependencies: { [SHARED]: "workspace:*", [UI]: "workspace:*", svelte: "^5.57.0" },
      devDependencies: { "@sveltejs/vite-plugin-svelte": "^7.3.0", "@tailwindcss/vite": "^4.3.3", "@tsconfig/svelte": "^5.0.8", "svelte-check": "^4.7.6", tailwindcss: "^4.3.3", typescript: "~6.0.2", vite: "^8.3.0" },
    }),
    { path: "index.html", contents: indexHtml(app).replace("__EXT__", "ts") },
    viteConfig([`import { svelte } from "@sveltejs/vite-plugin-svelte";`], "svelte()", app),
    { path: "svelte.config.js", contents: withBanner(`/** @type {import("@sveltejs/vite-plugin-svelte").SvelteConfig} */\nexport default {};\n`) },
    { path: "tsconfig.json", contents: `// ${BANNER}\n{\n  "extends": "@tsconfig/svelte/tsconfig.json",\n  "compilerOptions": { "target": "ES2023", "lib": ["ES2023", "DOM", "DOM.Iterable"], "types": ["svelte", "vite/client"], "allowArbitraryExtensions": true, "resolveJsonModule": true, "noEmit": true },\n  "include": ["src/**/*.ts", "src/**/*.svelte", "${HOST_GEN}/**/*.ts", "${HOST_GEN}/**/*.svelte"]\n}\n` },
    appCss(UI),
    { path: "src/main.ts", contents: withBanner(`import { mount } from "svelte";\nimport "./app.css";\nimport { bootScreen, screenKeyOf } from "${SHARED}/screens";\nimport App from "../${HOST_GEN}/App.svelte";\n\nconst screen = screenKeyOf(location);\nconst title = ${JSON.stringify(app.title)};\nbootScreen(screen, ${JSON.stringify(app.theme)}, title);\nmount(App, { target: document.getElementById("app")!, props: { screen, title } });\n`) },
    { path: `${HOST_GEN}/App.svelte`, contents: appSvelte },
    hostUrlAsset("url.svelte.ts", readFileSync(join(assets, "url.svelte.ts"), "utf8")),
  ];
}
