import { expect, test } from "bun:test";
import { join } from "node:path";
import { planBuild } from "@ui8kit/xgen-generator";
import { emitTwigBrick, jinja, kebab, twig } from "../src/index";

const plan = planBuild(join(import.meta.dir, "..", "..", "..", ".."));

test("every brick makes one template per part with the banner, the same twice", () => {
  for (const { brick } of plan.bricks) {
    if (brick.id === "ui.lucide-icon") continue; // an asset, not emitted
    const a = emitTwigBrick(brick, "x"), b = emitTwigBrick(brick, "x");
    expect(a.map((f) => f.contents)).toEqual(b.map((f) => f.contents));
    for (const part of brick.parts) {
      const f = a.find((x) => x.path === `ui/${brick.dir}/${kebab(part.name)}.html.twig`);
      expect(f?.contents.startsWith("{#- Code generated by xgen. DO NOT EDIT.")).toBe(true);
    }
  }
});

test("part names map to kebab file names", () => {
  expect(kebab("CardHeader")).toBe("card-header");
  expect(kebab("Button")).toBe("button");
});

test("the Jinja dialect prints the same tree with its own forms", () => {
  const button = plan.bricks.find((b) => b.brick.id === "ui.button")!.brick;
  const j = emitTwigBrick(button, "x", jinja).find((f) => f.path.endsWith(".html.j2"))!;
  expect(j.contents).toContain("|safe }}");
  expect(j.contents).not.toContain("|raw");
  expect(j.contents).toContain(" if ");
  expect(twig.ternary("c", "a", "b")).toBe("(c ? a : b)");
  expect(jinja.ternary("c", "a", "b")).toBe("(a if c else b)");
});

test("the twig package is a target of the plan with organisms, the PHP runtime and the ui8kit zones", () => {
  const t = plan.targets.find((x) => x.runtime === "twig")!;
  expect(t.files.some((f) => f.path === "blocks/pager.html.twig")).toBe(true);
  expect(t.files.some((f) => f.path === "php/Runtime.php")).toBe(true);
  const pkg = JSON.parse(t.files.find((f) => f.path === "package.json")!.contents) as { ui8kit: { kit: string[]; composition: string[]; blockRoot: string[] } };
  expect(pkg.ui8kit.kit).toEqual(["ui", "php"]);
  expect(pkg.ui8kit.composition).toEqual(["blocks"]);
  expect(pkg.ui8kit.blockRoot.length).toBeGreaterThan(0);
});
