// The Jinja2 package: the bricks and organisms printed by the Twig emitters through the jinja dialect (one include
// template per part, organisms in blocks/), the Python port of the ui_* helpers (py/ui8kit_jinja), the LucideIcon asset
// with its glyph registry, a parity harness (bin/parity.py), pyproject.toml and requirements.txt with Jinja2.
import { readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";
import { xgenPaths } from "@ui8kit/xgen-schema";
import type { LoadedBrick } from "@ui8kit/xgen-spec";
import type { Inputs } from "@ui8kit/xgen-screens";
import { BANNER, jsonFile, type GeneratedFile } from "@ui8kit/xgen-runtime-core";
import { blockRootOf, dialectOrganismFiles } from "./organisms";
import { header } from "@ui8kit/xgen-runtime-twig";
import { emitJinjaBrick, jinja, JINJA2_PACKAGE, JINJA2_REQUIREMENT } from "@ui8kit/xgen-runtime-jinja2";

export const JINJA2_DIR = "packages/jinja2/ui";
const ASSETS = join(import.meta.dir, "..", "..", "runtimes", "jinja2", "assets");
const asset = (name: string): string => readFileSync(join(ASSETS, name), "utf8");
const py = (src: string, source: string): string => `# ${BANNER}\n# Source: ${source}\n${src}`;
const json = (path: string, value: unknown): GeneratedFile => ({ path, contents: JSON.stringify({ "//": BANNER, ...(value as object) }, null, 2) + "\n" });

export function jinja2Files(bricks: LoadedBrick[], inputs: Inputs, xgenRoot: string, problems: string[] = []): GeneratedFile[] {
  const files: GeneratedFile[] = [];
  for (const b of bricks) {
    const source = `xgen/specs/ui/${b.specPath.split("/").pop()}`;
    if (b.brick.id === "ui.lucide-icon") {
      files.push({ path: `ui/${b.brick.dir}/lucide-icon${jinja.ext}`, contents: `${header(jinja, "xgen/runtimes/jinja2/assets/lucide-icon.html.j2", "LucideIcon (asset).")}\n${asset("lucide-icon.html.j2")}` });
      const { "//": note, ...icons } = JSON.parse(readFileSync(xgenPaths(xgenRoot).lucide, "utf8")) as Record<string, unknown>;
      files.push(json(`ui/${b.brick.dir}/lucide-icons.json`, { source: note, ...icons }));
      continue;
    }
    try { files.push(...emitJinjaBrick(b.brick, source, jinja)); } catch (e) { problems.push(`jinja2: ${(e as Error).message}`); }
  }
  for (const name of readdirSync(join(ASSETS, "py", "ui8kit_jinja")).filter((n) => n.endsWith(".py")).sort()) {
    files.push({ path: `py/ui8kit_jinja/${name}`, contents: py(asset(`py/ui8kit_jinja/${name}`), `xgen/runtimes/jinja2/assets/py/ui8kit_jinja/${name}`) });
  }
  files.push({ path: "bin/parity.py", contents: py(asset("parity.py"), "xgen/runtimes/jinja2/assets/parity.py") });
  files.push(...dialectOrganismFiles(bricks, inputs, problems, jinja, "jinja2"));
  const parts = bricks.reduce((n, b) => n + b.brick.parts.length, 0);
  files.push({ path: "requirements.txt", contents: `# ${BANNER}\n# Source: xgen/generator/src/jinja2.ts\n${JINJA2_REQUIREMENT}\n` });
  files.push({ path: "pyproject.toml", contents: [`# ${BANNER}`, `# Source: xgen/generator/src/jinja2.ts`, `[project]`, `name = "${JINJA2_PACKAGE}"`, `version = "0.0.0"`,
    `description = "Jinja2 templates of ui8kit (${bricks.length} bricks, ${parts} parts) generated by xgen from xgen/specs"`, `requires-python = ">=3.10"`, `dependencies = ["${JINJA2_REQUIREMENT}"]`, ``,
    `[build-system]`, `requires = ["setuptools>=68"]`, `build-backend = "setuptools.build_meta"`, ``, `[tool.setuptools.packages.find]`, `where = ["py"]`, ``].join("\n") });
  files.push({ path: ".gitignore", contents: `# ${BANNER}\n# the virtual environment of bun run check, and Python caches\n.venv/\n__pycache__/\n` });
  files.push(jsonFile("package.json", {
    name: "@ui8kit/jinja2-ui", version: "0.0.0", private: true,
    description: `Jinja2 templates (${bricks.length} bricks, ${parts} parts) generated by xgen from xgen/specs; Python helpers in py/ui8kit_jinja.`,
    // the organisms share one folder, so the block-root zone lists the files the TypeScript packages keep in src/blocks plus their frame components
    ui8kit: { runtime: "jinja2", generated: true, kit: ["ui", "py"], composition: ["blocks"], blockRoot: blockRootOf(inputs, files, jinja.ext) },
  }));
  files.push({ path: "README.md", contents: [`<!-- ${BANNER} -->`, `# ${JINJA2_PACKAGE}`, ``,
    `[Jinja2](https://jinja.palletsprojects.com) templates **generated** by xgen from \`xgen/specs\`: ${bricks.length} bricks, ${parts} parts, and the blocks.`, ``,
    "Every file here starts with `Code generated by xgen. DO NOT EDIT.` Change the spec in `xgen/specs` and run `bun run build`.", ``,
    "```python", `import sys; sys.path.insert(0, "/path/to/packages/jinja2/ui/py")`, `from ui8kit_jinja import environment`, `env = environment("/path/to/packages/jinja2/ui")`,
    `print(env.get_template("ui/button/button.html.j2").render(p={"Variant": "outline"}, children="Save"))`, "```", ``,
    "In a template: `{{ ui_include('ui/button/button.html.j2', {'p': {'Variant': 'outline'}, 'children': label}) }}`. Brick props use the canonical",
    "names (`Variant`, `Class`, `Attrs`), block props the JSON names of the TypeScript props (`title`, `className`); `children` is markup.", ``,
    "The classes are the same Tailwind v4 utilities as the Svelte, React, Vue and Solid packages: import their `styles/index.css` in the app CSS and add `@source` for this folder.", ``].join("\n") });
  return files.sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
}
