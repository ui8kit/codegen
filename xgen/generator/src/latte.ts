// The Latte package: the bricks and organisms printed by the Twig emitters through the latte dialect (one template per
// part, organisms in blocks/), the Twig PHP helpers under the UI8Kit\Latte namespace with a Latte extension that
// registers them, the LucideIcon asset with its glyph registry, a parity harness (bin/parity.php) and composer.json
// requiring latte/latte.
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { xgenPaths } from "@ui8kit/xgen-schema";
import type { LoadedBrick } from "@ui8kit/xgen-spec";
import type { Inputs } from "@ui8kit/xgen-screens";
import { BANNER, jsonFile, type GeneratedFile } from "@ui8kit/xgen-runtime-core";
import { blockRootOf, dialectOrganismFiles } from "./organisms";
import { header, phpHelpers, PHP_SHARED_SOURCE } from "@ui8kit/xgen-runtime-twig";
import { emitLatteBrick, latte, LATTE_PACKAGE, LATTE_VERSION } from "@ui8kit/xgen-runtime-latte";

export const LATTE_DIR = "packages/latte/ui";
const ASSETS = join(import.meta.dir, "..", "..", "runtimes", "latte", "assets");
const asset = (name: string): string => readFileSync(join(ASSETS, name), "utf8");
/** a PHP file with the banner after the open tag */
const php = (src: string, source: string): string => src.replace(/^<\?php\n/, `<?php\n\n// ${BANNER}\n// Source: ${source}\n`);
const json = (path: string, value: unknown): GeneratedFile => ({ path, contents: JSON.stringify({ "//": BANNER, ...(value as object) }, null, 2) + "\n" });

export function latteFiles(bricks: LoadedBrick[], inputs: Inputs, xgenRoot: string, problems: string[] = []): GeneratedFile[] {
  const files: GeneratedFile[] = [];
  for (const b of bricks) {
    const source = `xgen/specs/ui/${b.specPath.split("/").pop()}`;
    if (b.brick.id === "ui.lucide-icon") {
      files.push({ path: `ui/${b.brick.dir}/lucide-icon${latte.ext}`, contents: `${header(latte, "xgen/runtimes/latte/assets/lucide-icon.latte", "LucideIcon (asset).")}\n${asset("lucide-icon.latte")}` });
      const { "//": note, ...icons } = JSON.parse(readFileSync(xgenPaths(xgenRoot).lucide, "utf8")) as Record<string, unknown>;
      files.push(json(`ui/${b.brick.dir}/lucide-icons.json`, { source: note, ...icons }));
      continue;
    }
    try { files.push(...emitLatteBrick(b.brick, source, latte)); } catch (e) { problems.push(`latte: ${(e as Error).message}`); }
  }
  // the helpers are shared with the Twig package, in this package's namespace; the extension is Latte's own
  for (const [name, src] of phpHelpers("Latte")) files.push({ path: `php/${name}`, contents: php(src, `${PHP_SHARED_SOURCE}/${name}`) });
  files.push({ path: "php/Extension.php", contents: php(asset("php/Extension.php"), "xgen/runtimes/latte/assets/php/Extension.php") });
  files.push({ path: "bin/parity.php", contents: php(asset("parity.php"), "xgen/runtimes/latte/assets/parity.php") });
  files.push(...dialectOrganismFiles(bricks, inputs, problems, latte, "latte"));
  const parts = bricks.reduce((n, b) => n + b.brick.parts.length, 0);
  files.push({ path: "composer.json", contents: JSON.stringify({
    name: LATTE_PACKAGE, description: `Latte templates of ui8kit (${bricks.length} bricks, ${parts} parts) generated by xgen from xgen/specs. ${BANNER}`,
    type: "library", license: "MIT", require: { php: ">=8.2", "latte/latte": LATTE_VERSION }, autoload: { "psr-4": { "UI8Kit\\Latte\\": "php/" } },
  }, null, 2) + "\n" });
  files.push({ path: ".gitignore", contents: `# ${BANNER}\n# composer install output: rebuilt by bun run check\nvendor/\ncomposer.lock\n` });
  files.push(jsonFile("package.json", {
    name: "@ui8kit/latte-ui", version: "0.0.0", private: true,
    description: `Latte templates (${bricks.length} bricks, ${parts} parts) generated by xgen from xgen/specs; PHP runtime in php/ (composer package ${LATTE_PACKAGE}).`,
    // the organisms share one folder, so the block-root zone lists the files the TypeScript packages keep in src/blocks plus their frame components
    ui8kit: { runtime: "latte", generated: true, kit: ["ui", "php"], composition: ["blocks"], blockRoot: blockRootOf(inputs, files, latte.ext) },
  }));
  files.push({ path: "README.md", contents: [`<!-- ${BANNER} -->`, `# ${LATTE_PACKAGE}`, ``,
    `[Latte](https://latte.nette.org) templates **generated** by xgen from \`xgen/specs\`: ${bricks.length} bricks, ${parts} parts, and the blocks.`, ``,
    "Every file here starts with `Code generated by xgen. DO NOT EDIT.` Change the spec in `xgen/specs` and run `bun run build`.", ``,
    "```php", `$latte = \\UI8Kit\\Latte\\Extension::engine('/path/to/packages/latte/ui');`, `echo $latte->renderToString('ui/button/button.latte', ['p' => ['Variant' => 'outline'], 'children' => 'Save']);`, "```", ``,
    "In a template: `{=ui_include('ui/button/button.latte', ['p' => ['Variant' => 'outline'], 'children' => $label])|noescape}`. Brick props use the canonical",
    "names (`Variant`, `Class`, `Attrs`), block props the JSON names of the TypeScript props (`title`, `className`); `children` is markup.", ``,
    "The classes are the same Tailwind v4 utilities as the Svelte, React, Vue and Solid packages: import their `styles/index.css` in the app CSS and add `@source` for this folder.", ``].join("\n") });
  return files.sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
}
